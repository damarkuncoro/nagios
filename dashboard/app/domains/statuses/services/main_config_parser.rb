# frozen_string_literal: true

module Statuses
  module Services
    # Adopts main configuration file parsing from base/config.c (read_main_config_file)
    # Reads, parses, validates, and serializes `nagios.cfg` directives and multi-value parameters.
    class MainConfigParser
      ARRAY_DIRECTIVES = %w[cfg_file cfg_dir resource_file broker_module].freeze
      BOOLEAN_DIRECTIVES = %w[
        enable_notifications
        execute_service_checks
        accept_passive_service_checks
        execute_host_checks
        accept_passive_host_checks
        enable_event_handlers
        check_external_commands
        retain_state_information
        use_retained_program_state
        use_retained_scheduling_info
        enable_flap_detection
        check_for_updates
        bare_update_checks
        process_performance_data
      ].freeze

      INTEGER_DIRECTIVES = %w[
        status_update_interval
        max_check_result_file_age
        max_check_result_reaper_time
        check_result_reaper_frequency
        interval_length
        retention_update_interval
        service_check_timeout
        host_check_timeout
        event_handler_timeout
        notification_timeout
        ocsp_timeout
        ochp_timeout
      ].freeze

      FLOAT_DIRECTIVES = %w[
        low_service_flap_threshold
        high_service_flap_threshold
        low_host_flap_threshold
        high_host_flap_threshold
      ].freeze

      class << self
        def parse(content)
          new.parse(content)
        end

        def parse_file(path)
          return {} unless File.exist?(path)

          new.parse(File.read(path))
        end

        def serialize(config_hash)
          new.serialize(config_hash)
        end
      end

      # Parses raw nagios.cfg content into structured hash (base/config.c: read_main_config_file)
      def parse(content)
        config = {
          'cfg_file' => [],
          'cfg_dir' => [],
          'resource_file' => [],
          'broker_module' => []
        }

        content.to_s.each_line do |line|
          line = line.strip
          next if line.empty? || line.start_with?('#') || line.start_with?(';')

          # Remove inline comments if not escaped
          clean_line = line.split(/(?<!\\)[#;]/).first.to_s.strip
          next if clean_line.empty?

          directive, value = clean_line.split('=', 2).map(&:strip)
          next unless directive && value

          directive_down = directive.downcase

          if ARRAY_DIRECTIVES.include?(directive_down)
            config[directive_down] ||= []
            config[directive_down] << value
          else
            config[directive_down] = cast_value(directive_down, value)
          end
        end

        config
      end

      # Serializes config hash back to nagios.cfg format
      def serialize(config_hash)
        lines = [
          '##############################################################################',
          '# NAGIOS.CFG - Generated by Nagios Core Modern Ruby Engine',
          '##############################################################################',
          ''
        ]

        # 1. Output Array Directives first (cfg_file, cfg_dir, etc.)
        ARRAY_DIRECTIVES.each do |arr_key|
          Array(config_hash[arr_key]).each do |val|
            lines << "#{arr_key}=#{val}"
          end
        end
        lines << '' if lines.last != ''

        # 2. Output remaining scalar directives
        config_hash.each do |key, val|
          next if ARRAY_DIRECTIVES.include?(key.to_s.downcase)

          formatted_val = format_value(key.to_s.downcase, val)
          lines << "#{key}=#{formatted_val}"
        end

        lines.join("\n") + "\n"
      end

      # Validates config directives against Nagios Core rules (base/config.c: pre_flight_check)
      def validate(config_hash)
        errors = []
        warnings = []

        # Validate flap thresholds
        low_svc = config_hash['low_service_flap_threshold']
        high_svc = config_hash['high_service_flap_threshold']
        if low_svc && high_svc && low_svc >= high_svc
          errors << "low_service_flap_threshold (#{low_svc}) must be strictly less than high_service_flap_threshold (#{high_svc})"
        end

        low_host = config_hash['low_host_flap_threshold']
        high_host = config_hash['high_host_flap_threshold']
        if low_host && high_host && low_host >= high_host
          errors << "low_host_flap_threshold (#{low_host}) must be strictly less than high_host_flap_threshold (#{high_host})"
        end

        # Check positive timeouts
        INTEGER_DIRECTIVES.each do |timeout_key|
          val = config_hash[timeout_key]
          if val && val <= 0
            errors << "#{timeout_key} must be a positive integer greater than zero (got #{val})"
          end
        end

        # Warnings for missing standard paths
        %w[log_file command_file status_file].each do |path_key|
          val = config_hash[path_key]
          if val.nil? || val.to_s.strip.empty?
            warnings << "Recommended directive '#{path_key}' is not defined"
          end
        end

        {
          valid: errors.empty?,
          errors: errors,
          warnings: warnings
        }
      end

      private

      def cast_value(directive, value)
        if BOOLEAN_DIRECTIVES.include?(directive)
          value.to_s.strip == '1' || value.to_s.strip.casecmp('true').zero?
        elsif INTEGER_DIRECTIVES.include?(directive)
          value.to_i
        elsif FLOAT_DIRECTIVES.include?(directive)
          value.to_f
        else
          value
        end
      end

      def format_value(directive, value)
        if BOOLEAN_DIRECTIVES.include?(directive)
          value ? '1' : '0'
        else
          value.to_s
        end
      end
    end
  end
end
