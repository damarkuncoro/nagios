# frozen_string_literal: true

module Statuses
  module Services
    # Adopts object configuration parsing and template inheritance from
    # common/objects.c and xdata/xodtemplate.c
    # Parses `define <type> { ... }` blocks (host, service, command, contact, hostgroup, etc.),
    # resolves `use` template inheritance, and serializes objects back to Nagios .cfg format.
    class ObjectConfigParser
      ConfigCatalog = Struct.new(
        :hosts,
        :services,
        :commands,
        :contacts,
        :hostgroups,
        :servicegroups,
        :contactgroups,
        :timeperiods,
        :templates,
        keyword_init: true
      ) do
        def total_objects
          hosts.size + services.size + commands.size + contacts.size + hostgroups.size + servicegroups.size + contactgroups.size + timeperiods.size
        end
      end

      SUPPORTED_TYPES = %w[
        host service command contact
        hostgroup servicegroup contactgroup
        timeperiod
      ].freeze

      class << self
        def parse(content, resolve_templates: true)
          new.parse(content, resolve_templates: resolve_templates)
        end

        def parse_file(file_path, resolve_templates: true)
          return empty_catalog unless File.exist?(file_path)

          new.parse(File.read(file_path), resolve_templates: resolve_templates)
        end

        def serialize(catalog)
          new.serialize(catalog)
        end
      end

      # Parses raw object configuration text (xdata/xodtemplate.c: xodtemplate_read_config_data)
      def parse(content, resolve_templates: true)
        return empty_catalog if content.nil? || content.to_s.strip.empty?

        raw_blocks = extract_blocks(content)

        templates = {}
        hosts = {}
        services = []
        commands = {}
        contacts = {}
        hostgroups = {}
        servicegroups = {}
        contactgroups = {}
        timeperiods = {}

        raw_blocks.each do |block|
          type = block[:type]
          data = block[:data]

          # Register template if marked with `name` or `register 0`
          if data['name'] || data['register'].to_s == '0'
            t_name = data['name'] || data['host_name'] || data['service_description'] || data['command_name']
            templates["#{type}:#{t_name}"] = data.dup if t_name
            next if data['register'].to_s == '0' # Do not register as active object
          end

          case type
          when 'host'
            hosts[data['host_name']] = data if data['host_name']
          when 'service'
            services << data if data['service_description']
          when 'command'
            commands[data['command_name']] = data if data['command_name']
          when 'contact'
            contacts[data['contact_name']] = data if data['contact_name']
          when 'hostgroup'
            hostgroups[data['hostgroup_name']] = data if data['hostgroup_name']
          when 'servicegroup'
            servicegroups[data['servicegroup_name']] = data if data['servicegroup_name']
          when 'contactgroup'
            contactgroups[data['contactgroup_name']] = data if data['contactgroup_name']
          when 'timeperiod'
            timeperiods[data['timeperiod_name']] = data if data['timeperiod_name']
          end
        end

        catalog = ConfigCatalog.new(
          hosts: hosts,
          services: services,
          commands: commands,
          contacts: contacts,
          hostgroups: hostgroups,
          servicegroups: servicegroups,
          contactgroups: contactgroups,
          timeperiods: timeperiods,
          templates: templates
        )

        resolve_inheritance!(catalog) if resolve_templates
        catalog
      end

      # Serializes catalog back to standard Nagios .cfg format
      def serialize(catalog)
        lines = [
          '##############################################################################',
          '# NAGIOS OBJECT DEFINITIONS',
          '# Generated by Nagios Core Modern Ruby Engine',
          '##############################################################################',
          ''
        ]

        serialize_map(lines, 'command', catalog.commands)
        serialize_map(lines, 'timeperiod', catalog.timeperiods)
        serialize_map(lines, 'contact', catalog.contacts)
        serialize_map(lines, 'contactgroup', catalog.contactgroups)
        serialize_map(lines, 'host', catalog.hosts)
        serialize_map(lines, 'hostgroup', catalog.hostgroups)
        serialize_array(lines, 'service', catalog.services)
        serialize_map(lines, 'servicegroup', catalog.servicegroups)

        lines.join("\n") + "\n"
      end

      private

      def extract_blocks(content)
        blocks = []
        current_type = nil
        current_data = {}
        in_block = false

        content.each_line do |line|
          cleaned = line.strip
          next if cleaned.empty? || cleaned.start_with?('#') || cleaned.start_with?(';')

          # Match `define <type> {` or `define <type>{`
          if cleaned =~ /\Adefine\s+([a-zA-Z0-9_-]+)\s*\{?\z/
            current_type = Regexp.last_match(1).downcase
            current_data = {}
            in_block = true
          elsif in_block && cleaned == '}'
            blocks << { type: current_type, data: current_data } if current_type
            in_block = false
            current_type = nil
            current_data = {}
          elsif in_block && (cleaned =~ /\A([a-zA-Z0-9_\-+]+)\s+(.+)\z/)
            key = Regexp.last_match(1)
            val = Regexp.last_match(2).strip
            # Remove inline comments
            val = val.split(/(?<!\\)[#;]/).first.to_s.strip
            current_data[key] = val unless val.empty?
          end
        end

        blocks
      end

      # Recursively resolves `use` template inheritance (xdata/xodtemplate.c: xodtemplate_resolve_objects)
      def resolve_inheritance!(catalog)
        resolve_collection_inheritance!('host', catalog.hosts.values, catalog.templates)
        resolve_collection_inheritance!('service', catalog.services, catalog.templates)
        resolve_collection_inheritance!('command', catalog.commands.values, catalog.templates)
        resolve_collection_inheritance!('contact', catalog.contacts.values, catalog.templates)
      end

      def resolve_collection_inheritance!(type, items, templates)
        items.each do |item|
          use_chain = Array(item['use']).flat_map { |u| u.to_s.split(',').map(&:strip) }
          use_chain.each do |tpl_name|
            parent = templates["#{type}:#{tpl_name}"]
            next unless parent

            # Parent attributes merge into item if not already set on item
            parent.each do |pk, pv|
              next if pk == 'name' || pk == 'register'

              item[pk] ||= pv
            end
          end
        end
      end

      def serialize_map(lines, type, map)
        Array(map).each do |_key, data|
          serialize_item(lines, type, data)
        end
      end

      def serialize_array(lines, type, array)
        Array(array).each do |data|
          serialize_item(lines, type, data)
        end
      end

      def serialize_item(lines, type, data)
        return unless data.is_a?(Hash) && !data.empty?

        lines << "define #{type} {"
        data.each do |k, v|
          lines << sprintf("    %-24s%s", k, v)
        end
        lines << "}\n"
      end

      def empty_catalog
        ConfigCatalog.new(
          hosts: {},
          services: [],
          commands: {},
          contacts: {},
          hostgroups: {},
          servicegroups: {},
          contactgroups: {},
          timeperiods: {},
          templates: {}
        )
      end
    end
  end
end
