# frozen_string_literal: true

module Statuses
  module Services
    # Adopts state retention reading and saving from base/sretention.c and xdata/xrddefault.c
    # Parses and serializes standard Nagios retention.dat state files.
    class StateRetention
      RetentionSnapshot = Struct.new(:info, :hosts, :services, :contacts, keyword_init: true) do
        def host_count
          hosts.size
        end

        def service_count
          services.values.sum { |s| s.is_a?(Hash) ? s.size : 1 }
        end
      end

      class << self
        # Parses retention.dat content (String or IO)
        def parse(content)
          return RetentionSnapshot.new(info: {}, hosts: {}, services: {}, contacts: {}) if content.blank?

          info = {}
          hosts = {}
          services = {}
          contacts = {}

          current_block = nil
          current_data = {}

          lines = content.is_a?(String) ? content.lines : content.each_line

          lines.each do |line|
            cleaned = line.strip
            next if cleaned.empty? || cleaned.start_with?('#')

            if cleaned.end_with?('{')
              current_block = cleaned.sub(/\{$/, '').strip
              current_data = {}
            elsif cleaned == '}'
              if current_block.present?
                commit_block(current_block, current_data, info, hosts, services, contacts)
              end
              current_block = nil
              current_data = {}
            elsif current_block && cleaned.include?('=')
              key, val = cleaned.split('=', 2).map(&:strip)
              current_data[key] = coerce_value(val)
            end
          end

          RetentionSnapshot.new(
            info: info,
            hosts: hosts,
            services: services,
            contacts: contacts
          )
        end

        # Loads and parses retention file from disk path
        def load_file(file_path)
          return nil unless File.exist?(file_path)

          content = File.read(file_path)
          parse(content)
        rescue StandardError => e
          Rails.logger.error("[StateRetention] Gagal membaca retention file: #{e.message}")
          nil
        end

        # Serializes state information back into standard Nagios retention.dat format
        def dump(hosts: {}, services: {}, info: {})
          io = StringIO.new

          io.puts "########################################"
          io.puts "# NAGIOS CORE RETENTION DATA FILE"
          io.puts "# Generated by Nagios Rails Dashboard"
          io.puts "########################################"

          now_ts = (Time.respond_to?(:current) ? Time.current : Time.now).to_i
          io.puts "info {"
          io.puts "  created=#{info['created'] || now_ts}"
          io.puts "  version=#{info['version'] || '4.4.6'}"
          io.puts "  last_update_check=#{info['last_update_check'] || now_ts}"
          io.puts "}"
          io.puts ""

          # 2. Hoststatus blocks
          hosts_list = hosts.is_a?(Hash) ? hosts.values : Array(hosts)
          hosts_list.each do |h|
            data = h.is_a?(Hash) ? h : (h.respond_to?(:to_h) ? h.to_h : {})
            name = fetch_field(data, :name, :host_name)
            next if name.blank?

            io.puts "hoststatus {"
            io.puts "  host_name=#{name}"
            io.puts "  has_been_checked=#{fetch_field(data, :has_been_checked, default: 1)}"
            io.puts "  current_state=#{fetch_field(data, :current_state, :status_code, :status, default: 0)}"
            state_type = fetch_field(data, :state_type, default: 'HARD')
            io.puts "  state_type=#{state_type == 'HARD' || state_type == 1 ? 1 : 0}"
            io.puts "  plugin_output=#{fetch_field(data, :plugin_output, default: '')}"
            io.puts "  performance_data=#{fetch_field(data, :performance_data, :perf_data, default: '')}"
            io.puts "  last_check=#{fetch_field(data, :last_check, default: 0).to_i rescue 0}"
            io.puts "  next_check=#{fetch_field(data, :next_check, default: 0).to_i rescue 0}"
            flapping_val = fetch_field(data, :flapping, :is_flapping, default: 0)
            io.puts "  is_flapping=#{flapping_val == true || flapping_val.to_s == '1' ? 1 : 0}"
            io.puts "  percent_state_change=#{fetch_field(data, :percent_state_change, default: 0.0)}"
            ack_val = fetch_field(data, :acknowledged, :problem_has_been_acknowledged, default: 0)
            io.puts "  problem_has_been_acknowledged=#{ack_val == true || ack_val.to_s == '1' ? 1 : 0}"
            io.puts "  notifications_enabled=#{fetch_field(data, :notifications_enabled, default: 1) == false ? 0 : 1}"
            io.puts "  active_checks_enabled=#{fetch_field(data, :checks_enabled, :active_checks_enabled, default: 1) == false ? 0 : 1}"
            io.puts "  scheduled_downtime_depth=#{fetch_field(data, :scheduled_downtime_depth, default: 0)}"
            io.puts "}"
            io.puts ""
          end

          # 3. Servicestatus blocks
          each_service_entry(services) do |h_name, s_data|
            desc = fetch_field(s_data, :description, :service_description)
            next if desc.blank?

            io.puts "servicestatus {"
            io.puts "  host_name=#{h_name}"
            io.puts "  service_description=#{desc}"
            io.puts "  has_been_checked=#{fetch_field(s_data, :has_been_checked, default: 1)}"
            io.puts "  current_state=#{fetch_field(s_data, :current_state, :status_code, :status, default: 0)}"
            state_type = fetch_field(s_data, :state_type, default: 'HARD')
            io.puts "  state_type=#{state_type == 'HARD' || state_type == 1 ? 1 : 0}"
            io.puts "  plugin_output=#{fetch_field(s_data, :plugin_output, default: '')}"
            io.puts "  performance_data=#{fetch_field(s_data, :performance_data, :perf_data, default: '')}"
            io.puts "  last_check=#{fetch_field(s_data, :last_check, default: 0).to_i rescue 0}"
            io.puts "  next_check=#{fetch_field(s_data, :next_check, default: 0).to_i rescue 0}"
            flapping_val = fetch_field(s_data, :flapping, :is_flapping, default: 0)
            io.puts "  is_flapping=#{flapping_val == true || flapping_val.to_s == '1' ? 1 : 0}"
            io.puts "  percent_state_change=#{fetch_field(s_data, :percent_state_change, default: 0.0)}"
            ack_val = fetch_field(s_data, :acknowledged, :problem_has_been_acknowledged, default: 0)
            io.puts "  problem_has_been_acknowledged=#{ack_val == true || ack_val.to_s == '1' ? 1 : 0}"
            io.puts "  notifications_enabled=#{fetch_field(s_data, :notifications_enabled, default: 1) == false ? 0 : 1}"
            io.puts "  active_checks_enabled=#{fetch_field(s_data, :checks_enabled, :active_checks_enabled, default: 1) == false ? 0 : 1}"
            io.puts "  scheduled_downtime_depth=#{fetch_field(s_data, :scheduled_downtime_depth, default: 0)}"
            io.puts "}"
            io.puts ""
          end

          io.string
        end

        # Dumps and saves retention data atomically to target path
        def save_file(file_path, hosts:, services:, info: {})
          content = dump(hosts: hosts, services: services, info: info)
          tmp_path = "#{file_path}.tmp.#{Process.pid}"

          File.write(tmp_path, content)
          File.rename(tmp_path, file_path)
          true
        rescue StandardError => e
          Rails.logger.error("[StateRetention] Gagal menyimpan file retensi: #{e.message}")
          File.unlink(tmp_path) if File.exist?(tmp_path) rescue nil
          false
        end

        private

        def fetch_field(data, *keys, default: nil)
          return default if data.nil?

          keys.each do |k|
            if data.respond_to?(k) && !data.is_a?(Hash)
              val = data.public_send(k)
              return val unless val.nil?
            end
            if data.is_a?(Hash)
              return data[k.to_s] if data.key?(k.to_s)
              return data[k.to_sym] if data.key?(k.to_sym)
            end
          end

          default
        end

        def commit_block(block_type, data, info, hosts, services, contacts)
          case block_type
          when 'info'
            info.merge!(data)
          when 'hoststatus'
            name = data['host_name']
            hosts[name] = data if name.present?
          when 'servicestatus'
            name = data['host_name']
            desc = data['service_description']
            if name.present? && desc.present?
              services[name] ||= {}
              services[name][desc] = data
            end
          when 'contactstatus'
            c_name = data['contact_name']
            contacts[c_name] = data if c_name.present?
          end
        end

        def coerce_value(val)
          return '' if val.nil?

          if val =~ /^-?\d+$/
            val.to_i
          elsif val =~ /^-?\d+\.\d+$/
            val.to_f
          else
            val
          end
        end

        def each_service_entry(services)
          if services.is_a?(Hash)
            services.each do |h_name, s_group|
              if s_group.is_a?(Hash)
                s_group.each do |_s_desc, s_data|
                  yield(h_name, s_data)
                end
              elsif s_group.is_a?(Array)
                s_group.each do |s_data|
                  yield(h_name, s_data)
                end
              end
            end
          elsif services.is_a?(Array)
            services.each do |s|
              s_data = s.is_a?(Hash) ? s : (s.respond_to?(:to_h) ? s.to_h : {})
              h_name = s_data[:host_name] || s_data['host_name']
              yield(h_name, s_data) if h_name.present?
            end
          end
        end
      end
    end
  end
end
