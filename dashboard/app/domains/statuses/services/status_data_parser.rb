# frozen_string_literal: true

module Statuses
  module Services
    # Adopts external status data reading and writing from common/statusdata.c and xdata/xsddefault.c
    # Parses and serializes Nagios Core runtime `status.dat` files including programstatus,
    # hoststatus, servicestatus, contactstatus, comments, and downtimes.
    class StatusDataParser
      StatusSnapshot = Struct.new(
        :info,
        :programstatus,
        :hosts,
        :services,
        :contacts,
        :comments,
        :downtimes,
        keyword_init: true
      ) do
        def host_count
          hosts.size
        end

        def service_count
          services.values.sum { |s| s.is_a?(Hash) ? s.size : 1 }
        end

        def problem_hosts
          hosts.values.select { |h| h['current_state'].to_i.positive? }
        end

        def problem_services
          services.values.flat_map do |s_map|
            s_map.is_a?(Hash) ? s_map.values.select { |s| s['current_state'].to_i.positive? } : []
          end
        end
      end

      INTEGER_KEYS = %w[
        created version modified_attributes_host modified_attributes_service
        current_state last_state last_hard_state state_type
        current_attempt max_attempts last_check next_check check_type
        has_been_checked problem_has_been_acknowledged acknowledgement_type
        scheduled_downtime_depth notifications_enabled checks_enabled
        event_handler_enabled flap_detection_enabled is_flapping
        last_notification current_notification_number
        comment_id entry_type entry_time persistent
        downtime_id start_time end_time fixed duration triggered_by
        nagios_pid program_start last_command_check
      ].freeze

      FLOAT_KEYS = %w[
        percent_state_change execution_time latency
      ].freeze

      class << self
        def parse(content)
          new.parse(content)
        end

        def parse_file(file_path)
          return nil unless File.exist?(file_path)

          new.parse(File.read(file_path))
        end

        def serialize(snapshot)
          new.serialize(snapshot)
        end
      end

      # Parses status.dat string or IO (xdata/xsddefault.c: xsddefault_read_status_data)
      def parse(content)
        return empty_snapshot if content.nil? || content.to_s.strip.empty?

        info = {}
        programstatus = {}
        hosts = {}
        services = {}
        contacts = {}
        comments = []
        downtimes = []

        current_block = nil
        current_data = {}

        lines = content.is_a?(String) ? content.lines : content.each_line

        lines.each do |line|
          cleaned = line.strip
          next if cleaned.empty? || cleaned.start_with?('#')

          if cleaned.end_with?('{')
            current_block = cleaned.sub(/\{$/, '').strip
            current_data = {}
          elsif cleaned == '}'
            if current_block && !current_block.empty?
              commit_block(current_block, current_data, info, programstatus, hosts, services, contacts, comments, downtimes)
            end
            current_block = nil
            current_data = {}
          elsif current_block && cleaned.include?('=')
            key, val = cleaned.split('=', 2).map(&:strip)
            current_data[key] = coerce_value(key, val)
          end
        end

        StatusSnapshot.new(
          info: info,
          programstatus: programstatus,
          hosts: hosts,
          services: services,
          contacts: contacts,
          comments: comments,
          downtimes: downtimes
        )
      end

      # Serializes snapshot back to status.dat format (xdata/xsddefault.c: xsddefault_save_status_data)
      def serialize(snapshot)
        lines = [
          '########################################',
          '# NAGIOS STATUS DATA FILE',
          '# Generated by Nagios Core Modern Ruby Engine',
          '########################################',
          ''
        ]

        # 1. info block
        if snapshot.info && !snapshot.info.empty?
          lines << 'info {'
          snapshot.info.each { |k, v| lines << "\t#{k}=#{v}" }
          lines << "}\n"
        end

        # 2. programstatus block
        if snapshot.programstatus && !snapshot.programstatus.empty?
          lines << 'programstatus {'
          snapshot.programstatus.each { |k, v| lines << "\t#{k}=#{v}" }
          lines << "}\n"
        end

        # 3. hoststatus blocks
        Array(snapshot.hosts).each do |_name, data|
          lines << 'hoststatus {'
          data.each { |k, v| lines << "\t#{k}=#{v}" }
          lines << "}\n"
        end

        # 4. servicestatus blocks
        Array(snapshot.services).each do |_h_name, s_map|
          next unless s_map.is_a?(Hash)

          s_map.each do |_s_desc, data|
            lines << 'servicestatus {'
            data.each { |k, v| lines << "\t#{k}=#{v}" }
            lines << "}\n"
          end
        end

        # 5. comments
        Array(snapshot.comments).each do |cmt|
          block_name = cmt['service_description'] ? 'servicecomment' : 'hostcomment'
          lines << "#{block_name} {"
          cmt.each { |k, v| lines << "\t#{k}=#{v}" }
          lines << "}\n"
        end

        # 6. downtimes
        Array(snapshot.downtimes).each do |dt|
          block_name = dt['service_description'] ? 'servicedowntime' : 'hostdowntime'
          lines << "#{block_name} {"
          dt.each { |k, v| lines << "\t#{k}=#{v}" }
          lines << "}\n"
        end

        lines.join("\n")
      end

      private

      def commit_block(block, data, info, prog, hosts, services, contacts, comments, downtimes)
        case block
        when 'info'
          info.merge!(data)
        when 'programstatus'
          prog.merge!(data)
        when 'hoststatus'
          name = data['host_name']
          hosts[name] = data if name
        when 'servicestatus'
          h_name = data['host_name']
          s_desc = data['service_description']
          if h_name && s_desc
            services[h_name] ||= {}
            services[h_name][s_desc] = data
          end
        when 'contactstatus'
          c_name = data['contact_name']
          contacts[c_name] = data if c_name
        when 'hostcomment', 'servicecomment'
          comments << data
        when 'hostdowntime', 'servicedowntime'
          downtimes << data
        end
      end

      def coerce_value(key, val)
        return val.to_i if INTEGER_KEYS.include?(key)
        return val.to_f if FLOAT_KEYS.include?(key)

        val
      end

      def empty_snapshot
        StatusSnapshot.new(
          info: {},
          programstatus: {},
          hosts: {},
          services: {},
          contacts: {},
          comments: [],
          downtimes: []
        )
      end
    end
  end
end
